"""Check model launch settings and exact preservation of saved assistant responses."""

import json

import pytest
from jinja2 import Template

from discovery_execution.cli.run import parse_arguments
from discovery_execution.harness.constants import DEFAULT_BATCH_SIZES, DEFAULT_BLOCKS, SUPPORTED_MODELS
from discovery_execution.vllm.constants import DEFAULT_PORT, KV_CACHE_DTYPE, MAX_PORT, PARALLELISM
from discovery_execution.vllm.serve import build_command


@pytest.mark.parametrize("model", SUPPORTED_MODELS)
def test_serving_command(model: str) -> None:
    """All model aliases use the configured cache and shared context without response parsers."""
    command = build_command(model, DEFAULT_PORT, None)
    assert command[:3] == ["vllm", "serve", SUPPORTED_MODELS[model]]
    assert command[command.index("--served-model-name") + 1] == model
    assert command[command.index("--max-model-len") + 1] == "81920"
    assert command[command.index("--kv-cache-dtype") + 1] == KV_CACHE_DTYPE[model]
    assert command[command.index(f"--{PARALLELISM[model]}-parallel-size") + 1] == "2"
    assert not {"--reasoning-parser", "--enable-auto-tool-choice", "--quantization"} & set(command)
    if model == "qwen3-1.7b":
        rope = json.loads(command[command.index("--hf-overrides") + 1])["rope_parameters"]
        assert rope["factor"] * rope["original_max_position_embeddings"] == 131072
        assert rope["rope_type"] == "yarn"
    else:
        assert "--hf-overrides" not in command
    if model.startswith("ministral"):
        assert command[command.index("--tokenizer-mode") + 1] == "mistral"


@pytest.mark.parametrize("port", [0, MAX_PORT + 1])
def test_invalid_port(port: int) -> None:
    """Reject ports that cannot identify a listening server."""
    with pytest.raises(ValueError, match="port"):
        build_command("qwen3-1.7b", port, None)


@pytest.mark.parametrize("model", SUPPORTED_MODELS)
@pytest.mark.parametrize("override", [None, 7])
def test_concurrency_selection(model: str, override: int | None) -> None:
    """Collection and serving share model defaults and honor explicit concurrency."""
    arguments = ["--model", model, "--competition", "aime", "--year", "2024",
                 "--experiment", "unaided", "--seeds", "0"]
    expected = DEFAULT_BATCH_SIZES[model][0]
    if override is not None:
        arguments.extend(["--batch-size", str(override)])
        expected = override
    config = parse_arguments(arguments)
    command = build_command(model, DEFAULT_PORT, override)
    assert config.batch_size == expected
    assert command[command.index("--max-num-seqs") + 1] == str(expected)


@pytest.mark.parametrize("model", SUPPORTED_MODELS)
def test_batch_scales_with_budget(model: str) -> None:
    """Longer budgets hold more KV cache per trajectory, so the default batch shrinks with k."""
    long_batch, short_batch = DEFAULT_BATCH_SIZES[model]
    sizes = [parse_arguments(["--model", model, "--competition", "aime", "--year", "2024",
                              "--experiment", "unaided", "--compute-multiplier-k", str(k),
                              "--seeds", "0"]).batch_size for k in range(1, DEFAULT_BLOCKS + 1)]
    oracle = parse_arguments(["--model", model, "--competition", "aime", "--year", "2024",
                              "--experiment", "oracle-execution", "--seeds", "0"])
    assert sizes[0] == min(short_batch, long_batch * DEFAULT_BLOCKS)
    assert sizes[-1] == oracle.batch_size == long_batch
    assert sizes == sorted(sizes, reverse=True)


@pytest.mark.parametrize("concurrency", [0, -1])
def test_invalid_concurrency(concurrency: int) -> None:
    """An explicit invalid limit must fail instead of selecting the model default."""
    with pytest.raises(ValueError, match="max-num-seqs"):
        build_command("qwen3-1.7b", DEFAULT_PORT, concurrency)


@pytest.mark.parametrize("output", ["<think>\nunfinished", "reasoning\n</think>\n\\boxed{42}", "  partial\n\n"])
def test_template_preserves_response_prefix(chat_template: Template, output: str) -> None:
    """Rendering saved output retains the original prompt plus every generated byte."""
    messages = [{"role": "user", "content": "Solve."}]
    initial = chat_template.render(messages=messages, add_generation_prompt=True, bos_token="<BOS>")
    messages.append({"role": "assistant", "content": output})
    saved = chat_template.render(messages=messages, add_generation_prompt=False, bos_token="<BOS>")
    assert saved.startswith(initial + output)
    messages.append({"role": "user", "content": "Critique."})
    critique = chat_template.render(messages=messages, add_generation_prompt=True, bos_token="<BOS>")
    assert critique.startswith(saved)
